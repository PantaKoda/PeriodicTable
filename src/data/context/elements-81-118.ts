import type {
  BiologicalRoleStatus,
  ElementContext,
  NativeOccurrenceStatus,
  UseStatus,
} from '../element-context-types'

type TextTriplet = readonly [en: string, sv: string, el: string]

const reviewedAt = '2026-08-24'

function elementContext(
  atomicNumber: number,
  occurrence: TextTriplet,
  occurrenceSources: string[],
  nativeStatus: NativeOccurrenceStatus,
  native: TextTriplet,
  nativeSources: string[],
  biologicalStatus: BiologicalRoleStatus,
  biological: TextTriplet,
  biologicalSources: string[],
  useStatus: UseStatus,
  uses: TextTriplet,
  useSources: string[],
): ElementContext {
  const text = ([en, sv, el]: TextTriplet) => ({ en, sv, el })

  return {
    atomicNumber,
    naturalOccurrence: { text: text(occurrence), sourceIds: occurrenceSources },
    nativeOccurrence: { status: nativeStatus, text: text(native), sourceIds: nativeSources },
    biologicalRole: { status: biologicalStatus, text: text(biological), sourceIds: biologicalSources },
    commonUses: { status: useStatus, text: text(uses), sourceIds: useSources },
    reviewedAt,
  }
}

function superheavyContext(atomicNumber: number, [enName, svName, elName]: TextTriplet): ElementContext {
  return elementContext(
    atomicNumber,
    [
      `${enName} has only been observed after laboratory synthesis; its isotopes are short-lived.`,
      `${svName} har endast observerats efter framställning i laboratorier; dess isotoper är kortlivade.`,
      `Το ${elName} έχει παρατηρηθεί μόνο μετά από σύνθεση σε εργαστήριο· τα ισότοπά του είναι βραχύβια.`,
    ],
    ['doe', 'rsc'],
    'laboratory-only',
    [
      `${enName} does not occur as a native material; only individual or very few manufactured atoms have been detected.`,
      `${svName} förekommer inte som gediget material; endast enstaka eller mycket få framställda atomer har detekterats.`,
      `Το ${elName} δεν απαντάται ως αυτοφυές υλικό· έχουν ανιχνευθεί μόνο μεμονωμένα ή ελάχιστα τεχνητά παραγόμενα άτομα.`,
    ],
    ['doe', 'rsc'],
    'none-known',
    [
      `No biological role is known for ${enName.toLowerCase()}; its short-lived radioactive atoms do not occur in living systems.`,
      `Ingen biologisk roll är känd för ${svName.toLowerCase()}; dess kortlivade radioaktiva atomer förekommer inte i levande system.`,
      `Δεν είναι γνωστός βιολογικός ρόλος για το ${elName.toLowerCase()}· τα βραχύβια ραδιενεργά άτομά του δεν απαντώνται σε ζωντανά συστήματα.`,
    ],
    ['doe', 'rsc'],
    'research-only',
    [
      `${enName} has no established practical use outside research into nuclear stability, decay, and chemical behavior.`,
      `${svName} har ingen etablerad praktisk användning utanför forskning om kärnstabilitet, sönderfall och kemiskt beteende.`,
      `Το ${elName} δεν έχει καθιερωμένη πρακτική χρήση πέρα από την έρευνα της πυρηνικής σταθερότητας, της διάσπασης και της χημικής συμπεριφοράς.`,
    ],
    ['doe', 'rsc'],
  )
}

