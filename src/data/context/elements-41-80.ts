import type {
  BiologicalRoleStatus,
  ElementContext,
  LocalizedText,
  NativeOccurrenceStatus,
  UseStatus,
} from '../element-context-types'

type Copy = readonly [en: string, sv: string, el: string]
type SourceOverrides = Partial<Record<'natural' | 'native' | 'biological' | 'uses', string[]>>

const localized = ([en, sv, el]: Copy): LocalizedText => ({ en, sv, el })

function elementContext(
  atomicNumber: number,
  naturalOccurrence: Copy,
  nativeStatus: NativeOccurrenceStatus,
  nativeOccurrence: Copy,
  biologicalStatus: BiologicalRoleStatus,
  biologicalRole: Copy,
  useStatus: UseStatus,
  commonUses: Copy,
  sources: SourceOverrides = {},
): ElementContext {
  return {
    atomicNumber,
    naturalOccurrence: {
      text: localized(naturalOccurrence),
      sourceIds: sources.natural ?? ['rsc'],
    },
    nativeOccurrence: {
      status: nativeStatus,
      text: localized(nativeOccurrence),
      sourceIds: sources.native ?? ['rsc'],
    },
    biologicalRole: {
      status: biologicalStatus,
      text: localized(biologicalRole),
      sourceIds: sources.biological ?? ['rsc'],
    },
    commonUses: {
      status: useStatus,
      text: localized(commonUses),
      sourceIds: sources.uses ?? ['rsc'],
    },
    reviewedAt: '2026-08-24',
  }
}

